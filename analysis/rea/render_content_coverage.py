#!/usr/bin/env python3
"""Render coverage.json (build_content_coverage.py) as Markdown."""
import json
import sys
from collections import Counter

data = json.load(open(sys.argv[1]))
out = []
emit = out.append

emit("# Per-scene content coverage (object, character and media assets)")
emit("")
emit("Date: 26 October 2026. Generated by `analysis/rea/build_content_coverage.py`")
emit("from the extracted per-scene engine tables (CA/CB/CO/CI/CY/CS/CF/CD/CE),")
emit("the CC scripts, the six ISO file listings and one player entry per scene.")
emit("")
emit("**A scene whose background opens is not automatically complete.** The")
emit("`arrival` line and the per-scene object/character sections are the actual")
emit("content; the layer line only says which picture is behind it.")
emit("")

# ---------------- aggregate ----------------
scenes = list(data)
ca_types = Counter()
for d in data.values():
    for x in d["static"]["ca"]:
        ca_types[x["type"]] += 1
total_ca = sum(ca_types.values())
drawn = sum(sum(c["drawn"] for c in d["runtime"].get("composed") or [])
            for d in data.values())
snap = sum(sum(c["skipped_snap"] for c in d["runtime"].get("composed") or [])
           for d in data.values())
noframe = sum(sum(c["skipped_no_frame"] for c in d["runtime"].get("composed") or [])
              for d in data.values())
hidden = sum(sum(c["skipped_hidden"] for c in d["runtime"].get("composed") or [])
             for d in data.values())
bg_only = []
for s, d in data.items():
    rt = d["runtime"]
    comp = rt.get("composed") or []
    drawn_here = sum(c["drawn"] for c in comp)
    active = [o for o in rt.get("objects", []) if o["active"]]
    if drawn_here == 0 and not active and rt.get("final", {}).get("hotspots", 0) == 0:
        bg_only.append(s)

emit("## How to read this")
emit("")
emit("- `arrival` = one player entry per scene, using the lowest-numbered shipped")
emit("  save for that scene when one exists (`-` = engine tables with the original")
emit("  zero pool, `0x42c8a0`). It is a reachable state, not necessarily the")
emit("  player's first state.")
emit("- `CA sprites` are the `engine/<scene>ca` animation assets. `type 255` is")
emit("  the original's NULL: `0x431b0f` skips every record command for it, so it")
emit("  is dead data, not a missing file. Type 0/1 are created on demand; 2/3 are")
emit("  preloaded by `0x40fd7b`.")
emit("- `object declarations` are the constant `0x72` hotspot definitions. `active`")
emit("  is the live `DAT_00464300[slot]+0x08` after the entry; `not at arrival`")
emit("  are declared hotspots the script has not enabled yet (legitimate hidden")
emit("  content, not forced visible).")
emit("- Missing media is listed against the six ISO listings; a missing `dialog`")
emit("  clip is a CD record without that AVI folder, not a broken conversation")
emit("  parser.")
emit("")
emit("## Summary")
emit("")
emit(f"- 44 scenes; **{total_ca} CA sprite assets** "
     f"(type 255 = {ca_types.get(255,0)}, type 0 = {ca_types.get(0,0)}, "
     f"type 1 = {ca_types.get(1,0)}, type 2 = {ca_types.get(2,0)}, "
     f"type 3 = {ca_types.get(3,0)}).")
emit(f"- At arrival the player draws **{drawn}** records in total, reports "
     f"**{noframe}** without a decodable frame, **{snap}** with the `+0x09 & 0x20` "
     f"flag (kind pass skips them; the implemented snap pass has no `+0x20` "
     f"frame in this data) and **{hidden}** with `flags & 0x40`.")
emit("- Type 255 is not a missing file: `0x431b0f` leaves the record slot NULL, "
     "so every record command for it is skipped (`skipped_node_commands`).")
emit("- `skipped_snap` means the record carries `+0x09 & 0x20`; the original "
     "draws such a record only through `0x43b216` phase 1, which needs a non-NULL "
     "`+0x20` frame. Every shipped save record with the flag has `+0x20 = 0xffff` "
     "and a save load sets `DAT_004859cd = 1` (phase 1 off), so this is not a "
     "hidden missing asset. `skipped_hidden` (`flags & 0x40`) is the original's "
     "own skip.")
emit("- Background-only arrivals (no drawn record, no active object, no "
     "hotspot): " + ", ".join(bg_only) + ".")
emit("")

# ---------------- arrival table ----------------
emit("## Arrival table")
emit("")
emit("| scene | save | entry | layer | drawn ids | no-frame/snap/hidden | hotspots | active objects / declared |")
emit("| --- | --- | --- | --- | --- | --- | --- | --- |")
for s, d in data.items():
    rt = d["runtime"]
    comp = rt.get("composed") or []
    ids = ",".join(str(i) for c in comp for i in c["drawn_ids"]) or "-"
    layer = ",".join(sorted({c["layer"] for c in comp})) or "-"
    stop = rt.get("stop", "")
    stop = stop.replace("stopped: ", "") if stop else "clean"
    if rt.get("error"):
        stop = "ERROR"
    drawn_n = sum(c["drawn"] for c in comp)
    nf = sum(c["skipped_no_frame"] for c in comp)
    sn = sum(c["skipped_snap"] for c in comp)
    hd = sum(c["skipped_hidden"] for c in comp)
    active = sum(1 for o in rt.get("objects", []) if o["active"])
    emit(f"| `{s}` | {rt.get('save') or '-'} | {stop} | {layer} | {ids} | "
         f"{nf}/{sn}/{hd} | {rt.get('final',{}).get('hotspots','?')} | "
         f"{active}/{len(d['declared_objects'])} |")
emit("")

# ---------------- problems ----------------
emit("## Assets that do not load")
emit("")
problems = []
for s, d in data.items():
    for b in d["backgrounds"]:
        if not b["present"]:
            problems.append((s, "background", b["name"]))
    for n in d["nodes"]:
        if not n["present"]:
            problems.append((s, "node", n["name"]))
    for x in d["static"]["ca"]:
        if not x["anim"]:
            problems.append((s, "anims", f"{x['name']} (type {x['type']})"))
    for x in d["conversations"]:
        if x["clips"] == 0:
            problems.append((s, "dialog clips", f"{x['name']} (ccb={x['ccb']})"))
    for x in d["sounds"]:
        if not x["present"]:
            problems.append((s, "sound", x["name"]))
    for x in d["videos"]:
        if not x["present"]:
            problems.append((s, "video", x["name"]))
emit("| scene | kind | name | why |")
emit("| --- | --- | --- | --- |")
for s, kind, name in problems:
    if kind == "background" and s.startswith("exam") and name.startswith("ex"):
        why = "expected: the close-up uses inventor/examine/<item>.jpg"
    elif kind == "background":
        why = "not on any of the six CDs (the script's CB entry names it)"
    elif kind == "node":
        why = "not on any of the six CDs (panorama id in the scene's CO table)"
    elif kind == "anims":
        why = "type 0/1 with neither .rle nor .avi on the CDs"
    elif kind == "dialog clips":
        why = "CD record has no dialog/<name> AVI folder (voice-only/CCB text)"
    elif kind == "sound":
        why = "referenced by the CS table but not shipped under sounds/ or copy2hd/sounds/"
    else:
        why = "not shipped"
    emit(f"| `{s}` | {kind} | `{name}` | {why} |")
emit("")
emit("Not in this table but important: `endGame`/`Emre2`/`Pxstart` are shipped")
emit("*only* under `copy2hd/sounds/`, which `port/scene.sh` does not extract. The")
emit("player's sound lookup therefore cannot open them until the extraction (or")
emit("the lookup) also covers that folder; the `0xc4`/`0xd1` path reports the")
emit("failure instead of hiding it.")
emit("")

# ---------------- per scene ----------------
# Missing counts for the findings block.
missing_counts = Counter(kind for _, kind, _ in problems)
scene_draw = [s for s, d in data.items()
              if sum(c["drawn"] for c in d["runtime"].get("composed") or []) > 0]
conv_scenes = [s for s, d in data.items() if d["conversations"]]
item_scenes = [s for s, d in data.items() if d["items"]]
emit("## Key findings")
emit("")
emit(f"- Only **{sum(1 for d in data.values() for x in d['static']['ca'] if x['type'] in (0,1,2,3))}"
     f"/{total_ca}** CA entries can ever create a record; the rest are type 255.")
emit(f"- At arrival only **{len(scene_draw)} scenes** draw any record "
     f"({', '.join(scene_draw)}); that is the actual sprite/character content, "
     "not the background.")
emit(f"- **{snap}** records carry the `+0x09 & 0x20` flag and are not drawn by "
     "the kind pass. This is **not missing art**: the snap pass only draws a "
     "record with a valid `+0x20` frame, and every such record in the shipped "
     "saves has `+0x20 = 0xffff` (NULL); after a save load `DAT_004859cd = 1` "
     "disables the pass entirely. The port now implements the pass "
     "(`+0x24/+0x26` position, `+0x20` frame, clears it after the one draw) and "
     f"reports `snap_drawn`; `skipped_hidden`={hidden}, "
     f"`skipped_no_frame`={noframe}.")
emit(f"- Background-only arrivals (no record, no active object, no hotspot): "
     f"{', '.join(bg_only)}. Opening their backdrop is *not* scene completion.")
emit(f"- Media gaps: 3 backgrounds are genuinely absent (ALGDoor2, BCCountr, "
     "EAPhne2) and 7 CB entries in the close-up scenes are expected placeholders "
     "(the close-up uses `inventor/examine/<item>.jpg`); 17 MZ2 panorama nodes "
     "(mz18/mz19/mz21..mz29/mz31..mz36) are not on the CDs while the extracted "
     "MZ01..MZ10/mz30 are; BC `bckill1`/`bckill2` are type 0 with no anims file; "
     "3 CD records have no dialog clip folder; 5 CS sounds are not shipped.")
emit(f"- Characters/dialogue records exist in {len(conv_scenes)} scenes "
     f"({', '.join(conv_scenes)}); item/character names exist in "
     f"{len(item_scenes)} scenes.")
emit("- A save's own active objects are now part of the click/active set: the")
emit("  earlier `hotspot_enabled`-only list hid objects the save had active")
emit("  (`0x40c02c` tests `DAT_00464300[slot]+0x08`). Arrival hotspot counts for")
emit("  AM/MAP/NB/VH/VT rise accordingly; the rectangles and actions still come")
emit("  from the scene's `0x72` table.")
emit("")
emit("## Per-scene content")
emit("")
for s, d in data.items():
    rt = d["runtime"]
    st = d["static"]
    comp = rt.get("composed") or []
    active = [o for o in rt.get("objects", []) if o["active"]]
    emit(f"### `{s}` (SHOW.LCC {d['index']})")
    emit("")
    emit(f"- arrival: save `{rt.get('save') or '-'}`, entry "
         f"`steps={rt.get('steps','?')} stopped_at={rt.get('stopped_at','?')}` "
         f"{rt.get('stop','') or 'clean'}, records={rt.get('records','?')}, "
         f"hotspots={rt.get('final',{}).get('hotspots','?')}, "
         f"layer `{','.join(sorted({c['layer'] for c in comp})) or 'none'}`.")
    emit(f"- drawn: " + (", ".join(
        f"{c['layer']} ids={','.join(map(str,c['drawn_ids'])) or '-'} "
        f"({c['drawn']} rec, {c['pixels']} px)" for c in comp) or "none") + ".")
    if any(c["skipped_no_frame"] or c["skipped_snap"] or c["skipped_hidden"]
           for c in comp):
        emit(f"- skipped: no_frame={sum(c['skipped_no_frame'] for c in comp)}, "
             f"snap={sum(c['skipped_snap'] for c in comp)}, "
             f"hidden={sum(c['skipped_hidden'] for c in comp)}.")
    ca_usable = [x for x in st["ca"] if x["type"] in (0, 1, 2, 3)]
    ca_dead = [x for x in st["ca"] if x["type"] == 255]
    emit(f"- CA sprites: {len(st['ca'])} entries, {len(ca_usable)} usable "
         f"(type 0/1 lazy, 2/3 preloaded), {len(ca_dead)} type-255 "
         f"(never created).")
    if ca_usable:
        emit("  - usable sprites: " + ", ".join(
            f"`{x['name']}`(t{x['type']}{'' if x['anim'] else ', NO ANIM'})"
            for x in ca_usable[:10]) +
            (f" ... +{len(ca_usable)-10}" if len(ca_usable) > 10 else ""))
    if ca_dead:
        emit(f"  - type-255 sprites: {len(ca_dead)} (record commands for these "
             "slots are guard-skipped by `0x431b0f`; the original never draws "
             "them either): " +
             ", ".join(f"`{x['name']}`" for x in ca_dead[:8]) +
             (" ..." if len(ca_dead) > 8 else ""))
    if st["record_ops"]:
        ids = sorted({x["id"] for x in st["record_ops"]})
        dead_ids = {i for i, x in enumerate(st["ca"]) if x["type"] == 255}
        required_dead = [i for i in ids if i in dead_ids]
        emit(f"  - record commands: {len(st['record_ops'])}; type-255 slots "
             f"requested: {len(required_dead)}"
             + (" (" + ", ".join(map(str, required_dead[:12])) + ")" if required_dead else "")
             + " -> skipped, not missing art.")
    conv = d["conversations"]
    if conv:
        emit(f"- conversation/character records: {len(conv)}; " + ", ".join(
            f"`{x['name']}`({x['clips']} clips" +
            ("" if x["ccb"] else ", NO CCB") + ")" for x in conv[:10]) +
            (" ..." if len(conv) > 10 else ""))
    items = d["items"]
    if items:
        with_icon = sum(1 for x in items if x["icon"])
        with_hot = sum(1 for x in items if x["hotitem"])
        emit(f"- item/character names (CI): {len(items)}; inventor TGA "
             f"{with_icon}/{len(items)}, hotitem TGA {with_hot}/{len(items)} "
             f"(0x407254 needs both before it pushes the line).")
    declared = d["declared_objects"]
    if declared:
        enabled = [o for o in declared if o["enabled"]]
        active_slots = {o["slot"] for o in active}
        active_decl = [o for o in declared if o["slot"] in active_slots]
        gated = [o for o in declared if o["slot"] not in active_slots]
        emit(f"- object declarations: {len(declared)}, script enables {len(enabled)} "
             f"somewhere; runtime objects active at arrival {len(active)} "
             f"(hotspot rectangles {rt.get('final',{}).get('hotspots','?')}).")
        for o in active_decl:
            extra = ""
            if o.get("chain_id") is not None:
                extra = f" chain={o['chain_id']}"
            elif o.get("asset"):
                extra = (f" item=`{o['asset']}` icon={o['icon_present']}"
                         f" hotitem={o['hotitem_present']}")
            emit(f"  - active slot {o['slot']} kind 0x{o['kind']:02x} label "
                 f"{o['label']} rect {o['x']},{o['y']} {o['w']}x{o['h']}{extra}")
        if gated:
            emit("  - declared but not at arrival (script-gated / legitimately "
                 "hidden): " + ", ".join(f"{o['slot']}" for o in gated[:20]) +
                 (f" ... +{len(gated)-20}" if len(gated) > 20 else ""))
        other = sorted({o["slot"] for o in active} - {o["slot"] for o in declared})
        if other:
            emit("  - active objects without a constant 0x72 declaration "
                 "(created by the save/script): " + ", ".join(map(str, other[:20])))
    emit("")

print("\n".join(out))
