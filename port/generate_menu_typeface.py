#!/usr/bin/env python3
"""Bake regular serif UI masks; Pillow is needed only to regenerate this header.

Usage: python generate_menu_typeface.py /path/to/LiberationSerif-Regular.ttf
Runtime C++ has no system font, FreeType, Pillow or asset-path dependency.
The rasterized font is named Byzantine Menu Serif; see licenses/menu-typeface-OFL.txt.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, __version__

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('font',type=Path)
parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parent/'include/byzantine/menu_typeface.hpp')
args=parser.parse_args()
# Host UI strings use utf8_to_turkish_game_text and SfnFont's Turkish lookup.
chars={i-0x20:chr(i) for i in range(0x20,0x7f)}
for byte,char in zip([0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xa7,0xa8,0xaa,0xab,0xac,0xad], 'ÇŞİĞÜÖçşığüö'):
    chars[byte-0x41]=char
parts=['''// Generated by generate_menu_typeface.py; do not edit the masks.
// Byzantine Menu Serif, rasterized from Liberation Serif Regular.
// Font masks: SIL OFL 1.1, see port/licenses/menu-typeface-OFL.txt.
#pragma once
#include "byzantine/text.hpp"
#include <cstdint>
namespace byzantine { namespace menu_typeface_data {
''',f'// Source SHA256: {hashlib.sha256(args.font.read_bytes()).hexdigest()}\n// Generator Pillow: {__version__}\n']
for size in (14,16):
    font=ImageFont.truetype(str(args.font),size)
    ascent,descent=font.getmetrics();height=ascent+descent
    glyphs=[];width=0
    for i in range(111):
        char=chars.get(i)
        advance=max(1,round(font.getlength(char))) if char else 0
        glyphs.append((width,0,advance,height if char else 0))
        width+=advance
    # Keep coverage inside each advance; Serif negative bearings must not
    # overwrite a neighbour's glyph in the packed atlas.
    image=Image.new('L',(width,height))
    for i,(x,y,advance,h) in enumerate(glyphs):
        if not advance: continue
        cell=Image.new('L',(advance,height))
        ImageDraw.Draw(cell).text((0,ascent),chars[i],font=font,fill=255,anchor='ls')
        image.paste(cell,(x,0))
    values=image.tobytes()
    parts.append(f'inline constexpr int width_{size}={width}, height_{size}={height};\n')
    parts.append(f'inline constexpr SfnGlyph glyphs_{size}[] = {{\n')
    parts.extend('    {%d,%d,%d,%d},\n'%g for g in glyphs)
    parts.append('};\n')
    parts.append(f'inline constexpr std::uint8_t coverage_{size}[] = {{\n')
    for at in range(0,len(values),32): parts.append('    '+','.join(map(str,values[at:at+32]))+',\n')
    parts.append('};\n')
parts.append('''} // namespace menu_typeface_data
// Built-in host UI only. Gameplay continues using the shipped SFN fonts.
inline SfnFont menu_typeface(bool heading = false) {
    using namespace menu_typeface_data;
    SfnFont font;
    font.glyph_count = 111;
    font.atlas_width = heading ? width_16 : width_14;
    font.atlas_height = heading ? height_16 : height_14;
    font.line_height = font.atlas_height;
    const auto* glyphs = heading ? glyphs_16 : glyphs_14;
    font.glyphs.assign(glyphs, glyphs + font.glyph_count);
    const auto* coverage = heading ? coverage_16 : coverage_14;
    font.gr.assign(coverage, coverage + font.atlas_width * font.atlas_height);
    font.bk.assign(font.gr.size(), 0);
    font.fill = 0;
    return font;
}
} // namespace byzantine
''')
args.output.write_text(''.join(parts))
print(args.output)
